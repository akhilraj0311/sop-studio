#!/usr/bin/env bash
# SOP Studio: FREE deploy (Firebase Spark plan, no billing account needed). Run in Google Cloud Shell:
#
#   bash deploy_free.sh YOUR_PROJECT_ID
#
# Firebase Hosting (app) + Firebase Auth + Firestore + Gemini via Firebase AI Logic (Gemini Developer API).
# Safe to re-run. For the Cloud Run version (needs billing) use deploy.sh instead.
set -euo pipefail
cd "$(dirname "$0")"
export CLOUDSDK_CORE_DISABLE_PROMPTS=1
[ -f .env ] && { set -a; source .env; set +a; }
PROJECT_ID="${1:-${PROJECT_ID:-$(gcloud config get-value project 2>/dev/null || true)}}"
[ -z "$PROJECT_ID" ] && { echo "Usage: bash deploy_free.sh YOUR_PROJECT_ID"; exit 1; }
REGION="${REGION:-asia-south1}"
GEMINI_MODELS="${GEMINI_MODELS:-gemini-flash-latest,gemini-3.8-flash}"
step() { echo; echo "━━ $* ━━"; }

step "1/5  Project $PROJECT_ID: enabling free APIs"
gcloud config set project "$PROJECT_ID" >/dev/null
gcloud services enable firebase.googleapis.com firestore.googleapis.com identitytoolkit.googleapis.com \
  firebasehosting.googleapis.com firebaserules.googleapis.com generativelanguage.googleapis.com \
  firebasevertexai.googleapis.com cloudresourcemanager.googleapis.com
echo "  ✓ APIs enabled"

step "2/5  Firestore database"
if gcloud firestore databases describe --database='(default)' >/dev/null 2>&1; then echo "  ✓ already exists"
else gcloud firestore databases create --database='(default)' --location="$REGION" --type=firestore-native >/dev/null && echo "  ✓ created in $REGION"; fi

step "3/5  Firebase web app, sign-in and security rules"
python3 setup_firebase.py init "$PROJECT_ID" - || { echo "✗ Fix the step above, then re-run."; exit 1; }
set -a; source .env; set +a

step "4/5  Writing the web config"
cat > static/config.js <<CFG
// Generated by deploy_free.sh. Firebase web config values are public identifiers, not secrets.
window.SOP_CONFIG = {
  apiKey: "${FIREBASE_API_KEY}", authDomain: "${FIREBASE_AUTH_DOMAIN}", projectId: "${PROJECT_ID}",
  appId: "${FIREBASE_APP_ID}", messagingSenderId: "${FIREBASE_MESSAGING_SENDER_ID}",
  geminiModels: "${GEMINI_MODELS}"
};
CFG
echo "  ✓ static/config.js"

step "5/5  Deploying to Firebase Hosting"
python3 deploy_hosting.py "$PROJECT_ID"   # uses your gcloud login (no `firebase login` needed)

cat <<MSG

══════════════════════════════════════════════════════════════
 ✅ Live app:  https://${PROJECT_ID}.web.app
 One-time: Firebase console → AI Logic → Get started → "Gemini Developer API"
   https://console.firebase.google.com/project/${PROJECT_ID}/ailogic
 Then open the app → "Try it as a guest" → "Load 3 demo SOPs".
══════════════════════════════════════════════════════════════
MSG
